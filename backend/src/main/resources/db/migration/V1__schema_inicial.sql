-- =============================================================================
-- Esquema inicial do Sinalize.
-- Corresponde ao estado final das migrations do back-end original (NestJS):
-- CreateInitialDatabaseSchema + RemoveDescPalavra.
-- =============================================================================

CREATE TABLE usuarios (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nome      VARCHAR(255) NOT NULL,
    email     VARCHAR(255) NOT NULL,
    senha     VARCHAR(72)  NOT NULL, -- hash BCrypt (60 caracteres)
    criado_em TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT pk_usuarios PRIMARY KEY (id),
    CONSTRAINT uk_usuarios_email UNIQUE (email)
);

CREATE TABLE categorias (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nome           VARCHAR(255) NOT NULL,
    descricao      VARCHAR(400) NOT NULL,
    criado_em      TIMESTAMP    NOT NULL DEFAULT now(),
    atualizado_em  TIMESTAMP,
    criado_por     BIGINT       NOT NULL,
    atualizado_por BIGINT,
    CONSTRAINT pk_categorias PRIMARY KEY (id),
    CONSTRAINT fk_categorias_criado_por FOREIGN KEY (criado_por)
        REFERENCES usuarios (id) ON DELETE RESTRICT,
    CONSTRAINT fk_categorias_atualizado_por FOREIGN KEY (atualizado_por)
        REFERENCES usuarios (id) ON DELETE SET NULL
);

CREATE TABLE palavras (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    palavra        VARCHAR(255) NOT NULL,
    criado_em      TIMESTAMP    NOT NULL DEFAULT now(),
    atualizado_em  TIMESTAMP,
    criado_por     BIGINT       NOT NULL,
    atualizado_por BIGINT,
    CONSTRAINT pk_palavras PRIMARY KEY (id),
    CONSTRAINT fk_palavras_criado_por FOREIGN KEY (criado_por)
        REFERENCES usuarios (id) ON DELETE RESTRICT,
    CONSTRAINT fk_palavras_atualizado_por FOREIGN KEY (atualizado_por)
        REFERENCES usuarios (id) ON DELETE SET NULL
);

-- Associação N:N entre palavras e categorias.
CREATE TABLE palavras_categorias (
    palavra_id   BIGINT NOT NULL,
    categoria_id BIGINT NOT NULL,
    CONSTRAINT pk_palavras_categorias PRIMARY KEY (palavra_id, categoria_id),
    CONSTRAINT fk_palavras_categorias_palavra FOREIGN KEY (palavra_id)
        REFERENCES palavras (id) ON DELETE CASCADE,
    CONSTRAINT fk_palavras_categorias_categoria FOREIGN KEY (categoria_id)
        REFERENCES categorias (id) ON DELETE CASCADE
);

CREATE INDEX idx_palavras_categorias_palavra ON palavras_categorias (palavra_id);
CREATE INDEX idx_palavras_categorias_categoria ON palavras_categorias (categoria_id);

CREATE TABLE quizzes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario BIGINT    NOT NULL,
    criado_em  TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT pk_quizzes PRIMARY KEY (id),
    CONSTRAINT fk_quizzes_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuarios (id)
);

-- Cada palavra sorteada para um quiz e a resposta do jogador.
CREATE TABLE quiz_palavras (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_quiz       BIGINT    NOT NULL,
    id_palavra    BIGINT    NOT NULL,
    acertou       BOOLEAN,
    respondido_em TIMESTAMP,
    CONSTRAINT pk_quiz_palavras PRIMARY KEY (id),
    CONSTRAINT fk_quiz_palavras_quiz FOREIGN KEY (id_quiz)
        REFERENCES quizzes (id) ON DELETE CASCADE,
    CONSTRAINT fk_quiz_palavras_palavra FOREIGN KEY (id_palavra)
        REFERENCES palavras (id) ON DELETE RESTRICT
);

CREATE INDEX idx_quiz_palavras_quiz ON quiz_palavras (id_quiz);
CREATE INDEX idx_quiz_palavras_palavra ON quiz_palavras (id_palavra);
